"""Draw the README hero from the audited Re = 1000, 257² production field.

The streamlines in ``assets/readme/hero.svg`` are contours of the committed
steady streamfunction, not an illustration. Contour levels follow Ghia, Ghia &
Shin (1982): negative levels trace the primary vortex, positive levels the
counter-rotating corner eddies. Paths are simplified to 0.25 SVG units, well
below one rendered pixel.
"""
from __future__ import annotations

import json
